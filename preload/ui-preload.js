// Bridge for Burrow's own interface (tab strip, toolbar, panels).
// Exposes a small, fixed API as window.burrow. No Node.js access leaks to the page.
const { contextBridge, ipcRenderer } = require('electron');

const send = (ch) => (...args) => ipcRenderer.send(ch, ...args);
const listen = (channel) => (cb) => {
  const fn = (_e, data) => cb(data);
  ipcRenderer.on(channel, fn);
  return () => ipcRenderer.removeListener(channel, fn);
};

contextBridge.exposeInMainWorld('burrow', {
  ready: send('ui:ready'),
  setLayout: (top, right, left) => ipcRenderer.send('ui:layout', { top, right, left }),
  setOverlay: (open) => ipcRenderer.send('ui:overlay', !!open),
  setPrefs: send('prefs:set'),
  openPrivate: send('window:private'),
  openWindow: send('window:new'),
  otherWindows: () => ipcRenderer.invoke('windows:others'),
  readClipboard: () => ipcRenderer.invoke('clip:read'),
  importer: {
    sources: () => ipcRenderer.invoke('import:sources'),
    run: (id, want) => ipcRenderer.invoke('import:run', id, want),
    addQuickLinks: (sites) => ipcRenderer.invoke('import:quicklinks', sites),
  },
  // Right-click menus on pages: Burrow shows them, and sends back only the chosen item.
  ctx: { onMenu: listen('ctx-menu'), run: send('ctx:run'), closed: send('ctx:closed') },
  onDropMarker: listen('drop-marker'),
  ask: send('ai:ask'),
  searchNewTab: send('tab:search'),
  allTabs: () => ipcRenderer.invoke('palette:tabs'),
  onPaletteOpen: listen('palette-open'),
  split: {
    with: send('split:with'),
    off: send('split:off'),
    swap: send('split:swap'),
    ratio: send('split:ratio'),
    onPick: listen('split-pick'),
  },
  reader: () => ipcRenderer.invoke('reader:toggle'),
  ai: {
    panel: send('ai:panel'),
    width: send('ai:width'),
    onState: listen('ai-panel'),
  },
  notes: {
    get: () => ipcRenderer.invoke('notes:get'),
    read: (host) => ipcRenderer.invoke('notes:read', host),
    set: send('notes:set'),
    all: () => ipcRenderer.invoke('notes:all'),
    exportAll: () => ipcRenderer.invoke('notes:export'),
    onChange: listen('notes-changed'),
  },
  onMochiSay: listen('mochi-say'),
  focus: {
    snooze: (site) => ipcRenderer.invoke('focus:snooze', site),
    eaten: send('focus:eaten'),
    session: send('focus:session'),
    setLimit: (site, minutes) => ipcRenderer.invoke('focus:limit', site, minutes),
    info: () => ipcRenderer.invoke('focus:info'),
    onTimeUp: listen('focus-timeup'),
    onState: listen('focus-state'),
  },
  stats: { clear: send('stats:clear') },
  openReport: send('report:open'),
  zoom: send('zoom:step'),
  find: {
    query: send('find:query'),
    stop: send('find:stop'),
    onResult: listen('find-result'),
    onOpen: listen('find-open'),
    onStep: listen('find-step'),
  },
  onBookmarks: listen('bookmarks'),
  tabs: {
    create: send('tab:new'),
    close: send('tab:close'),
    activate: send('tab:activate'),
    navigate: send('tab:navigate'),
    reopen: send('tab:reopen'),
    mute: send('tab:mute'),
    keepAwake: send('tab:keepawake'),
    volume: (id, volume, remember) => ipcRenderer.invoke('tab:volume', id, volume, remember),
    sleepNow: send('tabs:sleep-now'),
    move: send('tab:move'),
    detach: send('tab:detach'),
    dragHover: send('tab:drag-hover'),
    newAfter: send('tab:new-after'),
    reload: send('tab:reload'),
    duplicate: send('tab:duplicate'),
    sleep: send('tab:sleep'),
    closeOthers: send('tab:close-others'),
    closeRight: send('tab:close-right'),
    moveToWorkspace: send('tab:move-ws'),
    moveToWindow: send('tab:move-window'),
    pip: () => ipcRenderer.invoke('tab:pip'),
    onChange: listen('tabs'),
  },
  workspaces: {
    create: send('ws:new'),
    rename: send('ws:rename'),
    remove: send('ws:delete'),
    switchTo: send('ws:switch'),
  },
  nav: {
    back: send('nav:back'),
    forward: send('nav:forward'),
    reload: send('nav:reload'),
    stop: send('nav:stop'),
  },
  library: {
    toggleBookmark: send('bookmark:toggle'),
    removeBookmark: send('bookmark:remove'),
    editBookmark: send('bookmark:edit'),
    removeHistory: send('history:remove'),
    clearHistory: send('history:clear'),
    open: send('open:url'),
    bookmarks: (q) => ipcRenderer.invoke('lib:bookmarks', q),
    history: (q) => ipcRenderer.invoke('lib:history', q),
    suggest: (q) => ipcRenderer.invoke('lib:suggest', q),
    onChange: listen('library-changed'),
  },
  downloads: {
    open: send('dl:open'),
    show: send('dl:show'),
    cancel: send('dl:cancel'),
    pause: send('dl:pause'),
    clear: send('dl:clear'),
    onChange: listen('downloads'),
    onDone: listen('download-done'),
  },
  theme: {
    set: send('theme:set'),
    onChange: listen('theme'),
  },
  onFocusAddress: listen('focus-address'),
  onOpenPanel: listen('open-panel'),
});
